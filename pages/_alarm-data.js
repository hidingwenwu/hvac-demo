function $lsSet(key,v){try{localStorage.setItem(key,JSON.stringify(v));}catch(e){}}

/* 当前项目(主框架 fyProj) */
function $alarmCurProj(){
  const p=$lsGet('fyProj',null);
  return (p&&p.name)||'产品部测试-按小时预付费';
}

/* 通用代码库:内置 + 覆盖(原型预留,UI 不维护) */
function $alarmCodeOverrides(){return $lsGet('fyAlarmCodeLib',{});}
function $alarmCodeLib(){
  const ov=$alarmCodeOverrides();
  const map={};
  ALARM_CODE_LIB_BASE.forEach(e=>{map[e.brand+'|'+e.code]=Object.assign({},e);});
  Object.keys(ov).forEach(k=>{map[k]=ov[k];});
  return Object.keys(map).map(k=>map[k]);
}
/* 故障码匹配规则:
   ── 通用库存在 db/dn/0b 等小写码,也存在仅大小写不同、含义与等级各异的并存码
      (海信 EE=压缩机保护(故障) / Ee=EEPROM数据错误(提示),另有 B1/b1、B5/b5)。
   ── 因此:精确匹配(区分大小写)优先;精确不中时,若该品牌下与输入仅大小写不同的
      库内码唯一,按不区分大小写命中(容错手输大小写);若并存多个则严格区分、不猜测。 */
function $alarmCiSiblings(brand,code){
  const cu=String(code).trim().toUpperCase();
  return ALARM_CODE_LIB_BASE.filter(x=>x.brand===brand&&x.code.toUpperCase()===cu);
}
function $alarmKeyEq(storedKey,brand,code){
  const i=storedKey.indexOf('|');
  if(storedKey.slice(0,i)!==brand)return false;
  const sc=storedKey.slice(i+1).trim(),c=String(code).trim();
  if(sc===c)return true;
  if(sc.toUpperCase()!==c.toUpperCase())return false;
  return $alarmCiSiblings(brand,c).length<=1;   /* 大小写并存码(如 Ee/EE)严格区分,不互相命中 */
}
function $alarmCodeLookup(brand,code){
  const ov=$alarmCodeOverrides();
  const c=String(code).trim();
  const cu=c.toUpperCase();
  const tryBrand=b=>{
    if(ov[b+'|'+c])return ov[b+'|'+c];
    const exact=ALARM_CODE_LIB_BASE.find(x=>x.brand===b&&x.code===c);
    if(exact)return exact;
    const ovKeys=Object.keys(ov).filter(k=>{const i=k.indexOf('|');return k.slice(0,i)===b&&k.slice(i+1).trim().toUpperCase()===cu;});
    if(ovKeys.length===1)return ov[ovKeys[0]];
    const sib=$alarmCiSiblings(b,c);
    if(sib.length===1)return sib[0];
    return null;
  };
  return tryBrand(brand)||(brand!=='通用'?tryBrand('通用'):null);
}

/* ── 项目级故障码配置:项目新增(含档位调整) + 项目屏蔽
     项目生效 = 通用代码库 + 项目新增 − 项目屏蔽(按项目隔离) ── */
function $alarmProjCodeAll(){return $lsGet('fyAlarmProjCode',{});}
function $alarmProjCodeGet(proj){
  const saved=$alarmProjCodeAll()[proj];
  if(saved&&typeof saved==='object'){
    /* 存量数据防御:字段缺失时补默认结构 */
    return {
      adds:(saved.adds&&typeof saved.adds==='object')?saved.adds:{},
      blocks:Array.isArray(saved.blocks)?saved.blocks:[],
    };
  }
  const seed=ALARM_PROJ_CODE_SEED[proj];
  if(seed)return JSON.parse(JSON.stringify(seed));
  return {adds:{},blocks:[]};
}
function $alarmProjCodeSet(proj,cfg){
  const all=$alarmProjCodeAll();
  all[proj]=cfg;
  $lsSet('fyAlarmProjCode',all);
  $alarmNotifyParent();
}
/* 项目配置内按规范化键查找(兼容存量键大小写不一) */
function $alarmProjAdd(cfg,brand,code){
  const k=Object.keys(cfg.adds).find(x=>$alarmKeyEq(x,brand,code));
  return k?cfg.adds[k]:null;
}
function $alarmProjBlockedKey(cfg,brand,code){
  return cfg.blocks.find(x=>$alarmKeyEq(x,brand,code))||null;
}
/* 项目级故障码解析(字段级回退):选填缺省取通用库描述 */
function $alarmProjEntry(brand,code,proj){
  const uni=$alarmCodeLookup(brand,code);
  const add=$alarmProjAdd($alarmProjCodeGet(proj||$alarmCurProj()),brand,code);
  if(!add)return uni||null;
  const e=Object.assign({},uni||{brand,code,model:'',name:'',desc:'',advice:''});
  ['model','name','desc','advice'].forEach(f=>{if(add[f])e[f]=add[f];});
  e.level=+(add.level||(uni?uni.level:2));
  return e;
}
/* 项目级故障档位判定:0=本项目已屏蔽;否则 项目新增/调整 > 通用库 > 默认警示 */
function $alarmFaultLevelProj(f,proj){
  const cfg=$alarmProjCodeGet(proj||$alarmCurProj());
  if($alarmProjBlockedKey(cfg,f.brand,f.code))return 0;
  const add=$alarmProjAdd(cfg,f.brand,f.code);
  if(add)return +add.level||2;
  const e=$alarmCodeLookup(f.brand,f.code);
  return e?+e.level:2;
}
function $alarmFaultBlocked(f,proj){return $alarmFaultLevelProj(f,proj)===0;}
function $alarmFaultEntry(f){return $alarmCodeLookup(f.brand,f.code);}
/* 运维故障等级 */
function $alarmOpsLevel(r){return ALARM_OPS_CAT_LV[r.cat]||2;}

/* 处理状态(运维故障与空调故障共用,键=记录 id)
   ── 按项目隔离:fyAlarmStatus = { [项目名]: { [记录id]: {st,by,time,note,for} } }
   ── for=处理/忽略时该故障的「故障时间」:同类故障复发时故障时间前移,
      旧状态自动失效(复发重新计入未处理,并可再次触发推送) */
function $alarmStatusAll(){
  const all=$lsGet('fyAlarmStatus',{});
  const cur=all[$alarmCurProj()];
  return (cur&&typeof cur==='object')?cur:{};
}
function $alarmStatus(id){return $alarmStatusAll()[id]||null;}
/* 记录级有效状态:复发(故障时间与处理时不一致)后返回 null(视同未处理) */
function $alarmStatusOf(rec){
  const s=$alarmStatusAll()[rec.id];
  if(!s)return null;
  const occur=rec.last||rec.devTime||'';
  if(s.for&&s.for!==occur)return null;
  return s;
}
function $alarmSetStatus(id,st,note,by,occur){
  const all=$lsGet('fyAlarmStatus',{});
  const proj=$alarmCurProj();
  if(!all[proj]||typeof all[proj]!=='object')all[proj]={};
  all[proj][id]={st,by:by||'丁文武',time:$alarmNow(),note:note||'',for:occur||''};
  $lsSet('fyAlarmStatus',all);
  $alarmNotifyParent();
}
function $alarmNow(){
  const d=new Date();
  const p=n=>String(n).padStart(2,'0');
  return `${d.getFullYear()}-${p(d.getMonth()+1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`;
}

/* 项目是否计费项目(非计费项目不展示计费分摊相关内容) */
const ALARM_PROJ_BILL={'001':false};
function $alarmProjBill(proj){return ALARM_PROJ_BILL[proj]!==false;}

/* 未处理计数(铃铛/总览共用);opts.bill===false 时不含计费分摊 */
function $alarmCounts(opts){
  const withBill=!opts||opts.bill!==false;
  const proj=$alarmCurProj();
  const c={ops:0,ac:0,base:0,bill:0,ops1:0,ops2:0,ops3:0,ac1:0,ac2:0,ac3:0,lv1:0,lv2:0,lv3:0,total:0};
  ALARM_OPS_ITEMS.forEach(r=>{
    if($alarmStatusOf(r))return;
    if($alarmInMaint(r,proj))return;
    const t=ALARM_OPS_CATS[r.cat];
    if(t==='bill'&&!withBill)return;
    const lv=$alarmOpsLevel(r);
    c.ops++;c[t]++;c['ops'+lv]++;c['lv'+lv]++;
  });
  ALARM_AC_FAULTS.forEach(f=>{
    if($alarmStatusOf(f))return;
    if($alarmInMaint(f,proj))return;
    const lv=$alarmFaultLevelProj(f,proj);
    if(lv===0)return;
    c.ac++;c['ac'+lv]++;c['lv'+lv]++;
  });
  c.total=c.ops+c.ac;
  return c;
}

/* 今日新增(总览/铃铛共用):当日产生的故障记录数,与未处理计数同口径(项目屏蔽故障码不计入);
   opts.bill===false 时不含计费分摊 */
function $alarmTodayNew(opts){
  const withBill=!opts||opts.bill!==false;
  const proj=$alarmCurProj();
  const today=$alarmNow().slice(0,10);
  let n=0;
  ALARM_OPS_ITEMS.forEach(r=>{
    if(r.last.slice(0,10)!==today)return;
    if(!withBill&&ALARM_OPS_CATS[r.cat]==='bill')return;
    if($alarmInMaint(r,proj))return;
    n++;
  });
  ALARM_AC_FAULTS.forEach(f=>{
    if(f.devTime.slice(0,10)!==today)return;
    if($alarmFaultLevelProj(f,proj)===0)return;
    if($alarmInMaint(f,proj))return;
    n++;
  });
  return n;
}

/* 最近预警(跨类合并,按时间倒序);opts.bill===false 时不含计费分摊 */
function $alarmRecent(n,opts){
  const withBill=!opts||opts.bill!==false;
  const proj=$alarmCurProj();
  const list=[];
  ALARM_OPS_ITEMS.forEach(r=>{
    const catType=ALARM_OPS_CATS[r.cat];
    if(catType==='bill'&&!withBill)return;
    if($alarmInMaint(r,proj))return;
    const lv=$alarmOpsLevel(r);
    list.push({kind:'ops',level:lv,id:r.id,title:r.cat,obj:r.obj,info:r.info,time:r.last,done:!!$alarmStatusOf(r),gone:!!r.gone});
  });
  ALARM_AC_FAULTS.forEach(f=>{
    const lv=$alarmFaultLevelProj(f,proj);
    if(lv===0)return;
    if($alarmInMaint(f,proj))return;
    const e=$alarmProjEntry(f.brand,f.code,proj);
    list.push({kind:'ac',level:lv,id:f.id,title:f.code+' '+(e&&e.name?e.name:'未知故障'),obj:f.room+' '+f.addr,addr:f.addr,info:(e&&e.name?e.name:'未知故障')+' · '+ALARM_LEVELS[lv].lb,time:f.devTime,done:!!$alarmStatusOf(f)});
  });
  list.sort((a,b)=>a.time<b.time?1:-1);
  return list.slice(0,n||10);
}

/* 推送配置(按项目隔离;种子配置作为默认)
   maint=维护窗口:窗口期内产生的故障全局忽略(不计数、不进列表、不推送),关闭窗口后恢复。
   站内提醒由顶部铃铛红点承担(全局口径,不受推送配置影响),不设站内信通道。 */
function $alarmPushCfgDefault(){
  return {enabled:false,receivers:[],scope:{levels:[1],cats:['ops','ac']},
    strategy:{mode:'realtime',dailyTime:'09:00',freq24:true,dnd:{on:false,from:'22:00',to:'08:00',exemptL1:true}},
    maint:{on:false,from:'',to:'',note:''}};
}
function $alarmPushCfgAll(){return $lsGet('fyAlarmPushCfg',{});}
function $alarmPushCfgGet(proj){
  const saved=$alarmPushCfgAll()[proj];
  const base=ALARM_PUSH_CFG_SEED[proj]?JSON.parse(JSON.stringify(ALARM_PUSH_CFG_SEED[proj])):$alarmPushCfgDefault();
  if(!saved||typeof saved!=='object')return base;
  /* 存量数据防御:旧版本结构缺失字段时与默认结构逐层合并,避免下游裸解引用报错 */
  const d=$alarmPushCfgDefault();
  const cfg=Object.assign({},base,saved);
  cfg.receivers=Array.isArray(cfg.receivers)?cfg.receivers:[];
  cfg.scope=Object.assign({},base.scope||d.scope,(saved.scope&&typeof saved.scope==='object')?saved.scope:{});
  if(!Array.isArray(cfg.scope.levels))cfg.scope.levels=d.scope.levels.slice();
  if(!Array.isArray(cfg.scope.cats))cfg.scope.cats=d.scope.cats.slice();
  cfg.strategy=Object.assign({},base.strategy||d.strategy,(saved.strategy&&typeof saved.strategy==='object')?saved.strategy:{});
  cfg.strategy.dnd=Object.assign({},(base.strategy&&base.strategy.dnd)||d.strategy.dnd,(saved.strategy&&saved.strategy.dnd&&typeof saved.strategy.dnd==='object')?saved.strategy.dnd:{});
  if(cfg.strategy.mode!=='realtime'&&cfg.strategy.mode!=='daily')cfg.strategy.mode='realtime';
  cfg.maint=Object.assign({},base.maint||d.maint,(saved.maint&&typeof saved.maint==='object')?saved.maint:{});
  return cfg;
}

/* ── 维护窗口:故障时间落在窗口期内的记录全局忽略(计数/列表/最近/今日新增/推送均排除) ── */
function $alarmInMaint(rec,proj){
  const m=$alarmPushCfgGet(proj||$alarmCurProj()).maint;
  if(!m||!m.on||!m.from||!m.to)return false;
  const t=(rec.last||rec.devTime||'');
  const from=m.from.replace('T',' ')+':00';
  const to=m.to.replace('T',' ')+':59';
  return t>=from&&t<=to;
}
function $alarmPushCfgSet(proj,cfg){
  const all=$alarmPushCfgAll();
  all[proj]=cfg;
  $lsSet('fyAlarmPushCfg',all);
}

/* 推送记录:用户产生(测试推送等) + 种子,按时间倒序 */
function $alarmPushLogGet(){
  const user=$lsGet('fyAlarmPushLog',[]);
  return user.concat(ALARM_PUSH_LOG_SEED).sort((a,b)=>a.time<b.time?1:-1);
}
function $alarmPushLogAdd(row){
  const user=$lsGet('fyAlarmPushLog',[]);
  user.unshift(row);
  $lsSet('fyAlarmPushLog',user);
}

/* 持续时长:(异常消失时间 || 当前时间) - 故障时间 */
function $alarmDuration(last,gone){
  const parse=s=>new Date(s.replace(/-/g,'/')).getTime();
  const end=gone?parse(gone):Date.now();
  let mins=Math.max(0,Math.round((end-parse(last))/60000));
  const d=Math.floor(mins/1440);mins%=1440;
  const h=Math.floor(mins/60);const m=mins%60;
  if(d>0)return d+'天'+h+'小时';
  if(h>0)return h+'小时'+m+'分';
  return m+'分钟';
}

/* 状态变更后通知刷新铃铛:逐层上抛到顶层主框架
   (代码库以 iframe 嵌在故障推送/故障详情弹窗中时,parent 是中间页而非主框架,只发 parent 会被吞) */
function $alarmNotifyParent(){
  try{
    let w=window;
    while(w.parent&&w.parent!==w){
      w=w.parent;
      w.postMessage({alarmDirty:1},'*');
    }
  }catch(e){}
}

/* 子页面请求主框架跳转(q 为可选查询串,如 'tab=ac') */
function $alarmNav(id,q){
  if(window.parent&&window.parent!==window)window.parent.postMessage({nav:id,q:q||''},'*');
}
