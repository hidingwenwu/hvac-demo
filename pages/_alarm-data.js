/* ── 时间助手:mock 数据相对当前时间生成,保证"持续时长/今日新增/趋势"始终真实。
     基准时间取会话级快照(sessionStorage 共享):主框架与各 iframe 用同一条时间线,
     否则各窗口秒级偏差会导致故障时间不一致(状态"复发失效"判定/今日新增漂移)。 ── */
const $ADT_NOW=(()=>{
  try{
    const v=sessionStorage.getItem('fyAdtNow');
    if(v)return new Date(+v);
    const d=new Date();
    sessionStorage.setItem('fyAdtNow',String(d.getTime()));
    return d;
  }catch(e){return new Date();}
})();
function $adtFmt(t){const p=n=>String(n).padStart(2,'0');return `${t.getFullYear()}-${p(t.getMonth()+1)}-${p(t.getDate())} ${p(t.getHours())}:${p(t.getMinutes())}:${p(t.getSeconds())}`;}
function $adtAgo(d,h){return $adtFmt(new Date($ADT_NOW.getTime()-(d*24+(h||0))*3600000));}

